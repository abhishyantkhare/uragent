create table public.reading_room_books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  category text not null check (category in ('book', 'essay')),
  note text not null
);

alter table public.reading_room_books enable row level security;
grant select on public.reading_room_books to anon, authenticated;
create policy "Public reading collection" on public.reading_room_books
  for select to anon, authenticated using (true);

